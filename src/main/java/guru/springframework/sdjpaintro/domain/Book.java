package guru.springframework.sdjpaintro.domain;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;

@Entity
public class Book {

    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)
    private Long id;

    private String title;
    private String isbn;
    private String publisher;

    // Constructors
    public Book() {
    }

    public Book(String title, String isbn, String publisher) {
        this.title = title;
        this.isbn = isbn;
        this.publisher = publisher;
    }

    /*
    This is an equals implementation for a JPA entity whose ID is generated by the database.

    The same object is always equal to itself.

    Two different Book instances are equal only when this book has a non-null ID matching the other book’s ID. Thus,
    two unsaved books are not equal just because their fields match.

    Using instanceof rather than getClass() is generally friendlier to JPA proxy subclasses.

    The main trade-off is that equality can change when a book is persisted and receives its ID. Your constant
    hashCode() strategy helps keep an entity findable in a HashSet across that transition, but causes hash collisions.
    This approach is a good fit when database identity is what defines a book’s equality.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Book other)) return false;

        return getId() != null && getId().equals(other.getId());
    }

    /*
    It’s a valid, conservative choice for a JPA entity with a database-generated ID. hashCode() stays the same before
    and after the ID is assigned, so a Book added to a HashSet before persistence remains findable afterward.
    It also satisfies the contract: if two books are equal by ID, they have the same hash code.

    The trade-off is that every Book has the same hash code, causing collisions and potentially slower lookups in large
    hash-based collections. For typical entity use this may be acceptable; avoid hashing directly from the generated ID,
    since that ID can change after persistence.

    This is a JPA-safe hash strategy that avoids hash instability caused by mutable fields
     */
    @Override
    public int hashCode() {
        return Book.class.hashCode();
    }

    // Getters and Setters
    public Long getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getIsbn() {
        return isbn;
    }

    public void setIsbn(String isbn) {
        this.isbn = isbn;
    }

    public String getPublisher() {
        return publisher;
    }

    public void setPublisher(String publisher) {
        this.publisher = publisher;
    }
}
